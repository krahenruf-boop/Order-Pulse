import assert from 'node:assert/strict';
import {createAovSettingsDraft} from '../static/materials/aov-monitor.js';
const rules=Object.fromEntries(['24h','48h','72h','7d'].map(w=>[w,{lower:'20',upper:'80',drop_pct:null,rise_pct:null,min_orders:10}]));
const product={family_id:'f1',name:'腰带扣',skus:['H1','H1*2'],rules};
const shop={id:'1',name:'店铺一',monitor:true,push:true,mapping_confirmed:true,miaoshou_shop_id:'m1',miaoshou_shop_name:'店铺一',currency:'BRL',sku_aliases:{tms:{},miaoshou:{H2:'H1*2'}},products:[product]};
const config={revision:3,enabled:true,shops:[shop]};
const stores=[{id:'1',name:'店铺一'},{id:'2',name:'店铺二'},{id:'3',name:'店铺三'}];
const catalog=[{family_id:'f1',product_name:'腰带扣',member_skus:['H1','H1*2']},{family_id:'f2',product_name:'眼霜',member_skus:['E1']}];
const draft=createAovSettingsDraft(config,stores,catalog);
assert.equal(draft.value.shops.length,3,'all directory shops appear without adding');
assert.deepEqual(draft.payload(),config,'merely listing shops preserves saved scope');
assert.equal(draft.value.shops[1].monitor,false);
draft.setShop('2','monitor',true);draft.selectProduct('2','f2',true);
assert.deepEqual(draft.value.shops[1].products[0].skus,['E1'],'SKUs come from catalog');
assert.equal(draft.value.shops[1].products[0].rules['24h'].lower,null,'no business thresholds seeded');
draft.setShop('2','push',true);draft.setShop('2','monitor',false);
assert.equal(draft.value.shops[1].push,false,'unmonitored shop cannot push');
draft.value.shops[0].products[0].display_name='H标腰带扣';
draft.selectProduct('1','f1',false);draft.selectProduct('1','f1',true);
assert.equal(draft.value.shops[0].products[0].display_name,'H标腰带扣');
assert.deepEqual(draft.value.shops[0].products[0].rules,rules,'uncheck/recheck retains draft thresholds');
assert.equal(draft.value.shops[0].sku_aliases.miaoshou.H2,'H1*2');
assert.equal(draft.payload().shops.length,2,'untouched unchecked shop not sent');
assert.equal(config.shops[0].products[0].display_name,undefined,'cancel cannot mutate original settings');
assert.equal(config.shops.length,1);
console.log('PASS: all shops, generated SKUs, retained draft, selection, push guard, unchanged saved scope and cancel');
